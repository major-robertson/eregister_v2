<div style="margin-top: 16pt;">
    <div class="keep">
        <p class="center" style="margin-bottom: 2pt;"><strong>NOTICE TO OWNER OF REAL PROPERTY</strong></p>
        <p class="center"><strong>NOTICE TO CONTRACTOR OR SUBCONTRACTOR, IF APPLICABLE</strong></p>

        <p>The owner's real estate may be subject to sale to satisfy the amount asserted by this claim. However, the owner's real estate cannot be sold until the facts and issues which form the basis of this claim are decided in a legal proceeding before a court of law. The lien claimant is required by law to commence suit to enforce this claim.</p>
    </div>

    <p>The claimant filing this lien claim shall forfeit all rights to enforce the lien claim and shall be required to discharge the lien claim of record, if the claimant fails to bring an action in the Superior Court, in the county in which the real property is situated, to establish the lien claim:</p>

    <table class="item">
        <tr><td class="n">1.</td><td>Within one year of the date of the last provision of work, services, material or equipment, payment for which the lien claim was filed; or</td></tr>
    </table>
    <table class="item">
        <tr><td class="n">2.</td><td>Within 30 days following receipt of written notice, by personal service or certified mail, return receipt requested, from the owner or community association, contractor, or subcontractor against whom a lien claim is filed, as appropriate, requiring the claimant to commence an action to establish the lien claim.</td></tr>
    </table>

    <p>You will be given proper notice of the proceeding and an opportunity to challenge this claim and set forth your position. If, after the owner (and/or contractor or subcontractor) has had the opportunity to challenge this lien claim, the court of law enters a judgment against any of you and in favor of the claimant filing this lien claim, and thereafter judgment is not paid, the owner's real estate may then be sold to satisfy the judgment. A judgment against a community association for a claim of work, services, material or equipment pursuant to a contract with that community association cannot be enforced by a sale of real estate.</p>

    <p>The owner may choose to avoid subjecting the real estate to sale by the owner (or contractor) by either:</p>

    <table class="item">
        <tr><td class="n">1.</td><td>paying the claimant and obtaining a discharge of lien claim from the claimant, by which the owner will lose the right to challenge this lien claim in a legal proceeding before a court of law; or</td></tr>
    </table>
    <table class="item">
        <tr><td class="n">2.</td><td>causing the lien claim to be discharged by filing a surety bond or making a deposit of funds as provided for in section 31 of P.L.1993, c.318 (C.2A:44A-31), by which the owner will retain the right to challenge this lien claim in a legal proceeding before a court of law.</td></tr>
    </table>
</div>

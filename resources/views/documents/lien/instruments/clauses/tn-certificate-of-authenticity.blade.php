    § 66-24-101(d)(3). A register records a copy of an electronic document (a
    paper copy of an electronic record, such as an online-notarized instrument,
    or a scan sent by e-recording, (d)(2)) only with this certification, signed
    by a licensed attorney or the custodian of the original and notarized; it
    "must be in the following form and the text of the certification must be in

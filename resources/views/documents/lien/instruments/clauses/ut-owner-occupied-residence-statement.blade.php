<div class="notice-box" style="font-weight: normal;">
    <p>The following notice applies only if the property described above is an owner-occupied residence (Utah Code § 38-1a-502(2)(i); Utah Admin. Code R156-38a-108).</p>
    <p><strong>PROTECTION AGAINST LIENS AND CIVIL ACTION.</strong> Notice is hereby provided in accordance with Section 38-11-108 of the Utah Code that under Utah law an "owner" may be protected against liens being maintained against an "owner-occupied residence" and from other civil action being maintained to recover monies owed for "qualified services" performed or provided by suppliers and subcontractors as a part of this contract, if either section (1) or (2) is met:</p>
    <p>(1)(a) the owner entered into a written contract with an original contractor, a factory built housing retailer, or a real estate developer;</p>
    <p>(b) the original contractor was properly licensed or exempt from licensure under Title 58, Chapter 55, Utah Construction Trades Licensing Act at the time the contract was executed; and</p>
    <p>(c) the owner paid in full the contracting entity in accordance with the written contract and any written or oral amendments to the contract; or</p>
    <p>(2) the amount of the general contract between the owner and the original contractor totals no more than $5,000.</p>
    <p style="margin-bottom: 0;">(3) An owner who can establish compliance with either section (1) or (2) may perfect the owner's protection by applying for a Certificate of Compliance with the Division of Occupational and Professional Licensing. The application is available at www.dopl.utah.gov/rlrf.</p>
</div>

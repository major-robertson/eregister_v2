<div class="notice-box">
    <p class="center">Notice to Property Owner</p>
    <p>If bills are not paid in full for the labor, professional services, materials, machinery, fixtures or tools furnished, or to be furnished, a mechanic's lien leading to the loss, through court foreclosure proceedings, of all or part of your property being improved may be placed against the property. You may wish to protect yourself against this consequence by either:</p>
    <p>1. Requiring your contractor to furnish a conditional waiver and release pursuant to Arizona Revised Statutes section 33-1008, subsection D, paragraphs 1 and 3 signed by the person or firm giving you this notice before you make payment to your contractor.</p>
    <p>2. Requiring your contractor to furnish an unconditional waiver and release pursuant to Arizona Revised Statutes section 33-1008, subsection D, paragraphs 2 and 4 signed by the person or firm giving you this notice after you make payment to your contractor.</p>
    <p style="margin-bottom: 0;">3. Using any other method or device that is appropriate under the circumstances.</p>
</div>

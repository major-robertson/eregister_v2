    Kansas warning statement, owner's acknowledgment. Instead of the mailing,
    K.S.A. 60-1103a(b)(2) lets the claimant hold "a copy of a statement signed
    and dated by any one owner of the property stating that the general
    contractor or the claimant had given the warning statement conforming
    with this section to one such owner of the property" (verified against
    ksrevisor.gov on 2026-09-30). The statute sets no wording, so this is
    house wording that tracks it. Printed after the claimant's signature.
--}}
